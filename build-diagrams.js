#!/usr/bin/env node
/* Compiles the TikZ diagrams in diagrams/*.tex into diagrams.js (const DIAGRAMS = { id: '<svg…>' }).
   Needs latex + dvisvgm (MiKTeX or TeX Live) on PATH. Only changed files are rebuilt.
   Usage:  node build-diagrams.js          build changed diagrams
           node build-diagrams.js --all    rebuild everything
           node build-diagrams.js degree   rebuild just these ids */
const fs = require('fs'), path = require('path'), crypto = require('crypto'), { spawnSync } = require('child_process');

const SRC = path.join(__dirname, 'diagrams'), OUT = path.join(SRC, 'build');
const CACHE = path.join(OUT, 'cache.json'), TARGET = path.join(__dirname, 'diagrams.js');
const args = process.argv.slice(2), forceAll = args.includes('--all'), only = args.filter(a => !a.startsWith('--'));

fs.mkdirSync(OUT, { recursive: true });
const preamble = fs.readFileSync(path.join(SRC, 'preamble.tex'), 'utf8');
let cache = {};
try { cache = JSON.parse(fs.readFileSync(CACHE, 'utf8')); } catch (e) { /* first build */ }

const ids = fs.readdirSync(SRC).filter(f => f.endsWith('.tex') && f !== 'preamble.tex').map(f => f.slice(0, -4)).sort();
for (const id of Object.keys(cache)) if (!ids.includes(id)) delete cache[id];

const wrap = body => [
  '\\documentclass[tikz,border=0pt]{standalone}',
  '\\usepackage{amsmath,amssymb}',
  '\\input{../preamble.tex}',
  '\\begin{document}', body.trim(), '\\end{document}', ''
].join('\n');
const run = (cmd, argv) => spawnSync(cmd, argv, { cwd: OUT, encoding: 'utf8' });

/* black -> ink, white -> paper, greys -> a mix, so diagrams follow the light/dark theme */
function colour(v, id) {
  if (v === 'none') return v;
  let h = v.replace('#', '');
  if (h.length === 3) h = h.split('').map(c => c + c).join('');
  const [r, g, b] = [0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16));
  if (!/^#[0-9a-f]{3,6}$/i.test(v) || r !== g || g !== b) throw new Error(`${id}: colour ${v} is not black, white or grey`);
  if (r === 0) return 'var(--ink)';
  if (r === 255) return 'var(--paper)';
  return `color-mix(in srgb,var(--ink) ${Math.round(100 - r / 2.55)}%,var(--paper))`;
}

function clean(svg, id) {
  let s = svg.replace(/<\?xml[^>]*>\s*/, '').replace(/<!--[\s\S]*?-->\s*/g, '');
  s = s.replace(/\bid='([^']+)'/g, `id='${id}-$1'`)
       .replace(/href='#([^']+)'/g, `href='#${id}-$1'`)
       .replace(/url\(#([^)]+)\)/g, `url(#${id}-$1)`);
  s = s.replace(/<(\w+)([^>]*?)(\/?)>/g, (m, tag, attrs, close) => {
    const style = [];
    attrs = attrs.replace(/\s(fill|stroke)='([^']*)'/g, (_, k, v) => { style.push(`${k}:${colour(v, id)}`); return ''; });
    return style.length ? `<${tag}${attrs} style='${style.join(';')}'${close}>` : m;
  });
  s = s.replace(/<svg([^>]*)>/, (m, a) => `<svg${a.replace(/\s(width|height)='[^']*'/g, '')} class='dia' role='img' aria-label='diagram' style='fill:var(--ink)'>`);
  return s.replace(/\n/g, '');
}

/* hash of what a diagram is built from; line endings normalised so git's CRLF conversion doesn't matter.
   check.js recomputes it to spot a stale diagrams.js. */
const sourceHash = (pre, body) => crypto.createHash('sha1').update((pre + body).replace(/\r\n/g, '\n')).digest('hex').slice(0, 12);

const failed = [];
let built = 0;
for (const id of ids) {
  const body = fs.readFileSync(path.join(SRC, id + '.tex'), 'utf8');
  const hash = sourceHash(preamble, body);
  const wanted = only.length ? only.includes(id) : forceAll || !cache[id] || cache[id].hash !== hash;
  if (!wanted) continue;
  fs.writeFileSync(path.join(OUT, id + '.tex'), wrap(body));
  const tex = run('latex', ['-interaction=nonstopmode', '-halt-on-error', id + '.tex']);
  if (tex.status !== 0) {
    const log = fs.existsSync(path.join(OUT, id + '.log')) ? fs.readFileSync(path.join(OUT, id + '.log'), 'utf8').split(/\r?\n/) : [];
    const i = log.findIndex(l => l.startsWith('!'));
    console.error(`✗ ${id}.tex\n  ${(i < 0 ? [tex.stdout.slice(-400)] : log.slice(i, i + 4)).join('\n  ')}`);
    failed.push(id);
    continue;
  }
  const dvi = run('dvisvgm', ['--no-fonts', '--bbox=papersize', '--precision=3', '--output=' + id + '.svg', id + '.dvi']);
  if (dvi.status !== 0) { console.error(`✗ ${id}: dvisvgm failed\n${dvi.stderr}`); failed.push(id); continue; }
  try {
    cache[id] = { hash, svg: clean(fs.readFileSync(path.join(OUT, id + '.svg'), 'utf8'), id) };
    built++;
  } catch (e) { console.error('✗ ' + e.message); failed.push(id); }
}

fs.writeFileSync(CACHE, JSON.stringify(cache));
const done = ids.filter(id => cache[id]);
const entries = done.map(id => `  ${JSON.stringify(id)}: ${JSON.stringify(cache[id].svg)}`);
const sources = JSON.stringify(Object.fromEntries(done.map(id => [id, cache[id].hash])));
fs.writeFileSync(TARGET, `/* Generated by build-diagrams.js from diagrams/*.tex. Do not edit by hand. */\nconst DIAGRAMS = {\n${entries.join(',\n')}\n};\nconst DIAGRAM_SOURCES = ${sources};\n`);

/* preview page: every diagram in light and dark, side by side. Open diagrams/build/preview.html
   (served or from disk); add #id1,id2 to the URL to show only some. */
fs.writeFileSync(path.join(OUT, 'preview.html'), `<!doctype html><meta charset="utf-8"><title>Diagram preview</title>
<style>body{margin:0;font:13px serif;background:#ccc}.g{display:grid;grid-template-columns:repeat(auto-fill,minmax(300px,1fr));gap:8px;padding:8px}
.c{background:var(--paper);color:var(--ink);padding:6px}.light{--ink:#111;--paper:#fff}.dark{--ink:#e9e9e6;--paper:#141414}
svg{width:100%;height:auto;display:block}h3{margin:0 0 4px;font-size:12px}</style>
<div class="g" id="g"></div><script src="../../diagrams.js"></script><script>
const only = location.hash.slice(1).split(',').filter(Boolean);
document.getElementById('g').innerHTML = Object.keys(DIAGRAMS).filter(id => !only.length || only.includes(id))
  .map(id => ['light', 'dark'].map(t => '<div class="c ' + t + '"><h3>' + id + '</h3>' + DIAGRAMS[id] + '</div>').join('')).join('');
</script>
`);
console.log(`${built} built, ${ids.length - built - failed.length} unchanged, ${failed.length} failed → diagrams.js (${entries.length} diagrams)`);
process.exit(failed.length ? 1 : 0);
